// Run against the two helper-managed Compose stacks; demo reset restores fixtures afterward.
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const password = (await readFile('.env.demo','utf8')).match(/^DEMO_PASSWORD=(.+)$/m)![1]!;
const browser = await chromium.launch({headless:true});
try {
  const context = await browser.newContext();
  const demo = await context.newPage(), normal = await context.newPage();
  await demo.goto('http://localhost:8081/account.html');
  await expect(demo.locator('.demo-banner')).toBeVisible();
  await demo.locator('#login-email').fill('resubmitted@demo.test');
  await demo.locator('#login-password').fill(password);
  await demo.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(demo.locator('.tag')).toHaveText('SUBMITTED');
  await demo.getByText('Submission history (2)',{exact:true}).click();
  await expect(demo.getByText('DEMO RULES v1',{exact:false})).toBeVisible();
  await expect(demo.getByText('DEMO RULES v2',{exact:false}).first()).toBeVisible();
  await normal.goto('http://localhost:8080/account.html');
  await expect(normal.locator('#signup')).toBeVisible();
  await normal.locator('#signup-email').fill(`compose-browser-${Date.now()}@example.test`);
  await normal.locator('#signup-password').fill('Compose-browser-password-42');
  await normal.getByLabel('Full in-game name').fill(`Compose ${Date.now().toString().split('').map(n=>String.fromCharCode(97+Number(n))).join('')}`);
  await normal.getByLabel('Why do you want to join?').fill('I enjoy coordinated guild groups.');
  await normal.getByRole('checkbox').check();
  await normal.getByRole('button',{name:'Create account & apply'}).click();
  await expect(normal.locator('.tag')).toHaveText('SUBMITTED');
  const cookies = await context.cookies();
  assert(cookies.some(c=>c.name==='mytikas.sid'));
  assert(cookies.some(c=>c.name==='mytikas.demo.sid'));
  await demo.reload(); await expect(demo.locator('.tag')).toHaveText('SUBMITTED');
  await normal.reload(); await expect(normal.locator('.tag')).toHaveText('SUBMITTED');
  await expect(normal.locator('.demo-banner')).toHaveCount(0);
  const oldDemoCookie = (await context.cookies()).find(c=>c.name==='mytikas.demo.sid')!.value;
  await demo.getByRole('button',{name:'Sign out'}).click();
  await expect(demo.locator('#login')).toBeVisible();
  await normal.reload();
  await expect(normal.locator('.tag')).toHaveText('SUBMITTED');
  assert((await context.cookies()).some(c=>c.name==='mytikas.sid'));
  assert.notEqual((await context.cookies()).find(c=>c.name==='mytikas.demo.sid')?.value,oldDemoCookie);
  await demo.locator('#login-email').fill('reopened@demo.test');
  await demo.locator('#login-password').fill(password);
  await demo.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(demo.locator('.tag')).toHaveText('REOPENED');
  await demo.getByLabel('Why do you want to join?').fill('I can raid on Tuesdays and enjoy helping new guildmates.');
  await demo.getByRole('checkbox').check();
  await demo.getByRole('button',{name:'Resubmit application'}).click();
  await expect(demo.locator('.tag')).toHaveText('SUBMITTED');
  console.log('✓ Compose browser: seeded login, banner, historical rules, reopened revision, simultaneous normal/demo sessions');
} finally { await browser.close(); }
